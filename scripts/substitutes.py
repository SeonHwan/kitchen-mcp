def build_rules():
    names = {i.name for i in build_ingredients()}
    rules = []
    for n, (src, dst, ratio, note) in enumerate(RULES, start=1):
        for name in (src, dst):
            if name not in names:
                raise ValueError(f"재료 사전에 없는 재료: {name}")
        rules.append({
            "id": f"S{n:03d}", "from": src, "to": dst, "ratio": ratio, "note": note,
            "text": f"{src} 대신 {dst}을(를) 쓸 수 있다. {src} 1g당 {dst} {ratio}g. {note}",
        })
    return rules


def validate(rules):
    if len(rules) != 40:
        raise ValueError(f"규칙은 40개여야 함: {len(rules)}")
    pairs = [(r["from"], r["to"]) for r in rules]
    if len(set(pairs)) != len(pairs):
        raise ValueError("같은 (원래, 대체) 쌍이 두 번 있음")
    if any(r["from"] == r["to"] or r["ratio"] <= 0 for r in rules):
        raise ValueError("자기 자신으로 대체하거나 비율이 0 이하인 규칙이 있음")


def main():
    rules = build_rules()
    validate(rules)
    Path("data").mkdir(exist_ok=True)
    Path("data/substitutes.json").write_text(json.dumps(rules, ensure_ascii=False, indent=2), encoding="utf-8")
    with open("data/substitutes.csv", "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["ID", "원래 재료", "대체 재료", "비율 (원래 1g당 대체 g)", "맛·식감 차이"])
        for r in rules:
            w.writerow([r["id"], r["from"], r["to"], r["ratio"], r["note"]])
    print("대체 재료 규칙", len(rules), "개 저장: data/substitutes.json, data/substitutes.csv")
    print("원래 재료 종류", len({r["from"] for r in rules}), "개")


if __name__ == "__main__":
    main()
