# 직전 대기 단계와 겹쳐 할 수 있는 단계 (레시피 이름 → 1부터 센 단계 번호).
# 해당 단계는 앞 단계의 결과가 필요 없는 독립 작업이다 (예: 육수 끓이는 동안 채소 볶기).
# 이 표시는 레시피를 읽고 사람(Claude)이 정한 값으로, 검증되지 않았다.
PARALLEL = {
    "떡볶이": [2, 3], "잡채": [3], "닭가슴살 샐러드": [2], "잔치국수": [2, 3],
    "비빔국수": [2, 3], "땅콩소스 비빔국수": [2, 3], "볼로네제 스파게티": [4],
    "크림파스타": [2, 3], "까르보나라": [2, 3], "알리오올리오": [2, 3],
    "파스타 그라탱": [2], "오븐 치킨 구이": [3], "단호박 수프": [3],
}


def parse_ingredients(text, unit_of):
    """'두부 300, 돼지고기 목살 200' → [{'name':..., 'amount':..., 'unit':...}]. 단위는 재료 사전에서 붙인다."""
    result = []
    for part in text.split(","):
        name, amount = part.strip().rsplit(" ", 1)
        amount = float(amount)
        if amount.is_integer():
            amount = int(amount)
        if name not in unit_of:
            raise ValueError(f"재료 사전에 없는 재료: {name}")
        result.append({"name": name, "amount": amount, "unit": unit_of[name]})
    return result


def build_recipes():
    unit_of = {i.name: i.unit for i in build_ingredients()}
    recipes = []
    for n, r in enumerate(RECIPES, start=1):
        parallel_steps = PARALLEL.get(r["name"], [])
        r["steps"] = [dict(s, parallel=(k in parallel_steps)) for k, s in enumerate(r["steps"], start=1)]
        equipment = []
        for step in r["steps"]:
            if step["equipment"] and step["equipment"] not in equipment:
                equipment.append(step["equipment"])
        recipes.append({
            "id": f"R{n:03d}",
            "name": r["name"],
            "servings": r["servings"],
            "tags": r["tags"],
            "equipment": equipment,
            "ingredients": parse_ingredients(r["ingredients"], unit_of),
            "steps": r["steps"],
        })
    return recipes


def validate(recipes):
    names = [r["name"] for r in recipes]
    if len(set(names)) != len(names):
        raise ValueError("레시피 이름 중복")
    for r in recipes:
        who = r["name"]
        bad_tags = set(r["tags"]) - TAGS
        if bad_tags:
            raise ValueError(f"{who}: 알 수 없는 태그 {bad_tags}")
        bad_eq = set(r["equipment"]) - EQUIPMENT
        if bad_eq:
            raise ValueError(f"{who}: 알 수 없는 장비 {bad_eq}")
        ing_names = [i["name"] for i in r["ingredients"]]
        if len(set(ing_names)) != len(ing_names):
            raise ValueError(f"{who}: 같은 재료가 두 번 들어감")
        if any(i["amount"] <= 0 for i in r["ingredients"]):
            raise ValueError(f"{who}: 분량은 양수여야 함")
        if len(r["steps"]) < 2 or any(s["minutes"] <= 0 for s in r["steps"]):
            raise ValueError(f"{who}: 단계가 2개 미만이거나 소요 시간이 0 이하")
        if r["steps"][0]["parallel"]:
            raise ValueError(f"{who}: 첫 단계는 겹쳐 할 앞 단계가 없음")
        for k, s in enumerate(r["steps"]):
            if s["parallel"] and not any(not p["active"] for p in r["steps"][:k]):
                raise ValueError(f"{who}: {k + 1}단계는 겹쳐 할 대기 단계가 앞에 없음")
    unknown = set(PARALLEL) - set(names)
    if unknown:
        raise ValueError(f"PARALLEL에 없는 레시피 이름: {unknown}")


def total_minutes(recipe):
    """모든 단계를 차례로 했을 때의 합계 (병렬 고려 없음)."""
    return sum(s["minutes"] for s in recipe["steps"])


def write_csv(recipes, path):
    columns = ["ID", "이름", "인분", "태그", "필요 장비", "재료", "순차 합계(분)", "조리 단계"]
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(columns)
        for r in recipes:
            ings = ", ".join(f"{i['name']} {i['amount']}{i['unit']}" for i in r["ingredients"])
            steps = " / ".join(
                f"{k}. {s['desc']}({s['minutes']}분{'' if s['active'] else ', 대기'}"
                f"{', ' + s['equipment'] if s['equipment'] else ''}{', 앞 대기와 동시 가능' if s['parallel'] else ''})"
                for k, s in enumerate(r["steps"], start=1))
            writer.writerow([r["id"], r["name"], r["servings"], ",".join(r["tags"]),
                             ",".join(r["equipment"]), ings, total_minutes(r), steps])


def main():
    recipes = build_recipes()
    validate(recipes)

    Path("data").mkdir(exist_ok=True)
    Path("data/recipes.json").write_text(
        json.dumps(recipes, ensure_ascii=False, indent=2), encoding="utf-8")
    write_csv(recipes, "data/recipes.csv")

    used = {i["name"] for r in recipes for i in r["ingredients"]}
    unused = [i.name for i in build_ingredients() if i.name not in used]
    tag_count = {}
    for r in recipes:
        for t in r["tags"]:
            tag_count[t] = tag_count.get(t, 0) + 1
    eq_count = {}
    for r in recipes:
        for e in r["equipment"]:
            eq_count[e] = eq_count.get(e, 0) + 1
    minutes = [total_minutes(r) for r in recipes]

    print("레시피", len(recipes), "개 저장: data/recipes.json, data/recipes.csv")
    print("태그별:", tag_count)
    print("장비별:", eq_count)
    print("순차 합계(분): 최소", min(minutes), "최대", max(minutes),
          "40분 이하", sum(1 for m in minutes if m <= 40), "개")
    print("레시피에 쓰인 재료", len(used), "개 / 안 쓰인 재료", len(unused), "개:", unused)


if __name__ == "__main__":
    main()
