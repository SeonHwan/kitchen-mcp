def build_ingredients():
    return [Ingredient(*row) for row in ROWS]


def validate(items):
    """사전 자체의 정합성을 검사한다. 어긋나면 ValueError."""
    names = [i.name for i in items]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        raise ValueError(f"재료 이름 중복: {dup}")
    for i in items:
        if i.category not in CATEGORIES:
            raise ValueError(f"{i.name}: 알 수 없는 분류 {i.category}")
        if i.unit not in UNITS:
            raise ValueError(f"{i.name}: 알 수 없는 단위 {i.unit}")
        if i.storage not in STORAGES:
            raise ValueError(f"{i.name}: 알 수 없는 보관법 {i.storage}")
        if i.unit == "g" and i.grams_per_unit != 1:
            raise ValueError(f"{i.name}: 단위가 g이면 grams_per_unit은 1이어야 함")
        if i.grams_per_unit <= 0 or i.price_per_unit <= 0:
            raise ValueError(f"{i.name}: 단위당 g과 가격은 양수여야 함")
        bad = set(i.allergens) - ALLERGENS
        if bad:
            raise ValueError(f"{i.name}: 알 수 없는 알레르기 분류 {bad}")


def main():
    items = build_ingredients()
    validate(items)

    out_path = Path("data/ingredients.json")
    out_path.parent.mkdir(exist_ok=True)
    out_path.write_text(
        json.dumps([i.to_dict() for i in items], ensure_ascii=False, indent=2), encoding="utf-8"
    )

    # 사람이 표로 보기 위한 CSV. 엑셀에서 한글이 깨지지 않도록 BOM 포함(utf-8-sig)으로 쓴다.
    csv_path = Path("data/ingredients.csv")
    # 필드 이름 → 한글 열 이름 (영양은 재료 1g당 값)
    columns = {
        "name": "이름", "category": "분류", "unit": "단위", "grams_per_unit": "단위당 g",
        "kcal": "열량 kcal", "protein_g": "단백질 g", "carb_g": "탄수화물 g",
        "fat_g": "지방 g", "sodium_mg": "나트륨 mg", "allergens": "알레르기",
        "price_per_unit": "단위당 가격(원)", "storage": "보관",
    }
    with open(csv_path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(columns.values()))
        writer.writeheader()
        for i in items:
            row = asdict(i)
            row["allergens"] = ",".join(i.allergens)
            # CSV의 영양 수치는 재료 1g당 값 (JSON은 100g당 그대로). 부동소수점 잡음은 반올림으로 제거
            for key in ("kcal", "protein_g", "carb_g", "fat_g", "sodium_mg"):
                row[key] = round(row[key] / 100, 5)
            writer.writerow({columns[k]: v for k, v in row.items()})

    by_category = {}
    for i in items:
        by_category[i.category] = by_category.get(i.category, 0) + 1
    print("재료", len(items), "개 저장:", out_path, ",", csv_path)
    print("분류별:", by_category)


